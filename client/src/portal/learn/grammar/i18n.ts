export type GKey = keyof typeof dict;

export function useGT() {
  const { locale } = useI18n();
  const t = (k: GKey, vars: Record<string, string | number> = {}) =>
    Object.entries(vars).reduce<string>((s, [a, b]) => s.replaceAll(`{${a}}`, String(b)), dict[k]?.[locale] ?? k);
  return { t, locale };
}
