export type LKey = keyof typeof dict;

export function useLT() {
  const { locale } = useI18n();
  const t = (k: LKey, vars: Record<string, string | number> = {}) =>
    Object.entries(vars).reduce<string>((s, [a, b]) => s.replaceAll(`{${a}}`, String(b)), dict[k]?.[locale] ?? k);
  return { t, locale };
}
